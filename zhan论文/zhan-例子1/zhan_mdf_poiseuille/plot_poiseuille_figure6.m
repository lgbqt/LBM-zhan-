du1000      = data1000(:,6);
duExact1000 = data1000(:,7);


% ============================================================
% 4. Recalculate Eq.(52) errors
%
% This is only for checking that the loaded files are correct.
% ============================================================

ErrU100 = ...
    sum(abs(u100 - uExact100)) ...
    / sum(abs(uExact100));

ErrDu100 = ...
    sum(abs(du100 - duExact100)) ...
    / sum(abs(duExact100));


ErrU500 = ...
    sum(abs(u500 - uExact500)) ...
    / sum(abs(uExact500));

ErrDu500 = ...
    sum(abs(du500 - duExact500)) ...
    / sum(abs(duExact500));


ErrU1000 = ...
    sum(abs(u1000 - uExact1000)) ...
    / sum(abs(uExact1000));

ErrDu1000 = ...
    sum(abs(du1000 - duExact1000)) ...
    / sum(abs(duExact1000));


fprintf('=============================================\n');
