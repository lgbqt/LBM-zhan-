% ------------------------------------------------------------
% 1. File names
% ------------------------------------------------------------

file100  = 'poiseuille_numerical_100to1_A.dat';
file500  = 'poiseuille_numerical_500to1_A.dat';
file1000 = 'poiseuille_numerical_1000to1_A.dat';


% ------------------------------------------------------------
% 2. Load data
% ------------------------------------------------------------

data100  = load(file100);
data500  = load(file500);
data1000 = load(file1000);


% ============================================================
% 3. Extract data
% ============================================================

% -------------------------
% 100 : 1
% -------------------------

y100       = data100(:,1);

u100       = data100(:,4);
uExact100  = data100(:,5);

du100      = data100(:,6);
duExact100 = data100(:,7);


% -------------------------
% 500 : 1
% -------------------------

y500       = data500(:,1);

u500       = data500(:,4);
uExact500  = data500(:,5);

